"""Serialize an internal PlannedRoute (P4) into the canonical ``keelson.Route`` (P5).

Maps per docs/KEELSON-INTEGRATION.md §2: keelson protos are primary; planner-only data (metrics,
cost weights, provenance, generation metadata) rides in a ``route-planner`` ``Extensions`` entry's
string attributes. Validation fields (``challenges``/``issues``) and ``hazard_zones`` are left for
P7; the RPC wiring + publish is P6. Requires the keelson monorepo SDK (``payloads.Route_pb2``).
"""

from __future__ import annotations

from .position import set_lat_lon

import time
import uuid

from . import vessel_profile as vp

MANUFACTURER = vp.MANUFACTURER


def _f(value, default=None):
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def route_from_planned(
    planned,
    *,
    profile: dict,
    optimization_goal: str | None,
    evidence: dict | None = None,
    route_id: str | None = None,
    created_at_ns: int | None = None,
    edition: int = 1,
):
    """Build a ``keelson.Route`` from a PlannedRoute + the planning context."""
    from keelson.payloads.Route_pb2 import Route

    from .enums import ARCHIPELAGO, COASTAL, LOXODROME, PLANNED, RECOMMENDED

    ts = created_at_ns if created_at_ns is not None else time.time_ns()
    route = Route(
        route_id=route_id or uuid.uuid4().hex,
        route_edition_number=edition,
        route_format_version="RTZ-1.2",
        version="0.1",
        status=RECOMMENDED if planned.status_hint == "RECOMMENDED" else PLANNED,
    )
    route.created_at.FromNanoseconds(ts)
    route.modified_at.FromNanoseconds(ts)

    # RouteInfo: vessel constraints + optimization method (reused), plus authorship/provenance.
    route.info.CopyFrom(vp.route_info_from_profile(profile, optimization_goal))
    route.info.name = profile.get("name") or f"{optimization_goal or 'planned'} route"
    route.info.author = "route-planner"
    route.info.author_organization = MANUFACTURER
    # keelson removed RouteInfo.change_history (the route's edition history lives on the
    # route_change_event subject now); keep the entry only where the installed SDK still has it.
    if "change_history" in route.info.DESCRIPTOR.fields_by_name:
        change = route.info.change_history.add()
        change.edition_number = edition
        change.description = "generated by keelson-processor-route-planner"
        change.at.FromNanoseconds(ts)

    # Waypoints + outgoing legs.
    preferred = _f(profile.get("preferred_speed_kn"))
    turn_radius = _f(profile.get("turn_radius_m"))
    min_speed = _f(profile.get("min_speed_kn"))
    max_speed = _f(profile.get("max_speed_kn"))
    ukc = _f(profile.get("min_under_keel_clearance_m"))
    safety_depth = (_f(profile.get("draught_m"), 0.0) or 0.0) + (ukc if ukc is not None else 0.5)
    op_context = ARCHIPELAGO if "archipelago" in (optimization_goal or "") else COASTAL

    waypoints = planned.waypoints or []
    for i, (lat, lon) in enumerate(waypoints):
        wp = route.waypoints.waypoint.add()
        wp.id = str(i + 1)  # a string since keelson made Waypoint.id one
        set_lat_lon(wp.position, lat, lon)
        if preferred is not None:
            wp.planned_sog_knots = preferred
        if turn_radius is not None:
            wp.radius_m = turn_radius
        wp.operational_context = op_context
        if i < len(waypoints) - 1:  # outgoing leg toward the next waypoint
            wp.leg.geometry_type = LOXODROME
            wp.leg.safety_depth_m = safety_depth
            wp.leg.safety_contour_m = safety_depth
            if ukc is not None:
                wp.leg.ukc_static_m = ukc
            if min_speed is not None:
                wp.leg.sog_min_knots = min_speed
            if max_speed is not None:
                wp.leg.sog_max_knots = max_speed

    # route-planner Extensions entry: profile fields (reused) + metrics + provenance + metadata.
    entry = vp.planner_extension_entry(profile)
    attrs = entry.attributes
    if optimization_goal:
        attrs["optimization_goal"] = optimization_goal
    for key, value in (planned.metrics or {}).items():
        attrs[key] = str(value)
    attrs["snapped_start"] = str(bool(planned.snapped_start)).lower()
    attrs["snapped_end"] = str(bool(planned.snapped_end)).lower()
    for kind, metres in (planned.cost_breakdown or {}).items():
        attrs[f"soft.{kind}"] = str(metres)
    # Per-leg geodesic metrics (Geod.inv, computed in pathfinding): two parallel CSV arrays aligned
    # to waypoint order — leg i is the outgoing leg from waypoint i, so len == n_waypoints - 1.
    # keelson.Leg has no native distance/bearing field, hence the Extensions (cf. chart_cells below).
    if planned.legs:
        attrs["leg_distances_m"] = ",".join(str(leg["distance_m"]) for leg in planned.legs)
        attrs["leg_bearings_deg"] = ",".join(str(leg["bearing_deg"]) for leg in planned.legs)
    provenance = (evidence or {}).get("provenance")
    if provenance is not None:
        cells = sorted(c for c in getattr(provenance, "cells", set()) if c)
        if cells:
            attrs["chart_cells"] = ",".join(cells)
        worst = getattr(provenance, "worst_chart_scale", None)
        if worst is not None:
            attrs["worst_chart_scale"] = str(worst)
    attrs["generated_at"] = str(ts)
    attrs["edited_after_validation"] = "false"
    route.extensions.entries.append(entry)

    return route


def routes_from_alternatives(
    planned_list,
    *,
    profile: dict,
    optimization_goal: str | None,
    evidence: dict | None = None,
    created_at_ns: int | None = None,
) -> list:
    """Serialize a list of PlannedRoutes to keelson.Routes (distinct route_ids; status from each)."""
    return [
        route_from_planned(
            planned,
            profile=profile,
            optimization_goal=optimization_goal,
            evidence=evidence,
            created_at_ns=created_at_ns,
        )
        for planned in planned_list
    ]
